"""
Build data/quran.db (SQLite) for Surah Al-Mulk (67) from the raw Tanzil + morphology files.

Run from the repo root:
    python scripts/build_db.py

What it does
  1. Reads data/raw/quran-simple.txt, en.sahih.txt, quran-morphology.txt (never modified).
  2. Drops the bismillah Tanzil prepends to ayah 1.
  3. Splits ayah text into words; stop-sign tokens (e.g. ۖ ۚ) are kept as `trail` on the previous
     word so the displayed Arabic is identical to Tanzil's.
  4. Aligns words with morphology by (ayah, word number) and refuses to build if they disagree.
  5. Adds the English word-by-word meaning (data/raw/english-wbw-translation.json) to each word and the
     transliteration (data/raw/en-transliteration-tajweed.json) to each ayah. Refuses to build if the
     word-by-word file does not line up exactly with our words.
  6. For every verb, looks up its past (maazi) and present/future (mudari) forms as they actually appear
     elsewhere in the Qur'an (from the same morphology file) - nothing is generated by grammar rules.
  7. Imports reciters (data/raw/recitations/) and tafsir (data/raw/tafsir/); see import_audio.py / import_tafsir.py.
  8. Applies manual fixes from data/corrections.csv (your verification log).
"""
import csv
import collections
import json
import sqlite3
import sys
import unicodedata
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))   # so the import_* helpers next to this file are found
import import_audio    # noqa: E402
import import_tafsir   # noqa: E402

ROOT_DIR = Path(__file__).resolve().parent.parent
RAW = ROOT_DIR / "data" / "raw"
DB_PATH = ROOT_DIR / "data" / "quran.db"
CORRECTIONS = ROOT_DIR / "data" / "corrections.csv"
RECITATIONS_DIR = RAW / "recitations"
TAFSIR_DIR = RAW / "tafsir"
RECITERS_CONFIG = ROOT_DIR / "data" / "reciters.json"
WBW_FILE = RAW / "english-wbw-translation.json"
TRANSLIT_FILE = RAW / "en-transliteration-tajweed.json"

SURAH = 67
N_AYAHS = 30
BISMILLAH_TOKENS = 4  # Tanzil prepends it to ayah 1 of every surah except 1 and 9
EDITABLE_FIELDS = {"root", "lemma", "pos_tag", "grammar", "gloss", "verified",
                   "past_form", "past_ref", "present_form", "present_ref"}


def has_letter(token):
    return any(unicodedata.category(c).startswith("L") for c in token)


def load_tanzil(path):
    d = {}
    for line in open(path, encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        s, a, text = line.rstrip("\n").split("|", 2)
        if int(s) == SURAH:
            d[int(a)] = text
    return d


def load_morph(path):
    """Returns {(ayah, word_no): [segment dicts]} for the surah."""
    words = collections.defaultdict(list)
    for line in open(path, encoding="utf-8"):
        if not line.startswith(f"{SURAH}:"):
            continue
        loc, form, tag, feats = line.rstrip("\n").split("\t")
        _, a, w, seg = map(int, loc.split(":"))
        kv, flags = {}, []
        for f in feats.split("|"):
            if ":" in f:
                k, v = f.split(":", 1)
                kv[k] = v
            else:
                flags.append(f)
        words[(a, w)].append(dict(seg=seg, form=form, tag=tag, root=kv.get("ROOT"),
                                  lemma=kv.get("LEM"), vform=kv.get("VF"),
                                  flags=flags, raw=feats))
    return words


def load_transliteration(path):
    """{ayah: text} for the surah. Source keys look like "67:3"."""
    data = json.load(open(path, encoding="utf-8"))
    return {a: data[f"{SURAH}:{a}"].strip() for a in range(1, N_AYAHS + 1)}


def load_wbw(path):
    """{ayah: [meaning of word 1, word 2, ...]}. Source keys look like "67:3:2".
    The source adds an extra last entry per ayah that is just the ayah number, e.g. "(3)"; it is dropped here
    (and checked) so the list lines up with the words."""
    data = json.load(open(path, encoding="utf-8"))
    out = {}
    for a in range(1, N_AYAHS + 1):
        items, i = [], 1
        while f"{SURAH}:{a}:{i}" in data:
            items.append(data[f"{SURAH}:{a}:{i}"].strip())
            i += 1
        if not items or items[-1] != f"({a})":
            raise SystemExit(f"word-by-word file: ayah {a} does not end with its ayah-number marker '({a})'")
        out[a] = items[:-1]
    return out


# Only the 3rd person masculine singular ("he did" / "he does") is used for the past/present display.
# Other persons are not safe to show: the corpus splits their subject endings into separate segments, so the
# stem alone would be a truncated, wrong-looking word (e.g. the stem of "we tested them" is just بَلَوْ).
SHOW_PERSON = "3MS"


def load_verb_forms(path):
    """Index every verb stem in the WHOLE Qur'an morphology file.
    Returns {(root, lemma, verb_form, passive): {tense: {form: [count, first_ref]}}}
    Only clean forms are kept:
      - 3rd person masculine singular only (SHOW_PERSON)
      - present = indicative only (no subjunctive/jussive endings)
      - words with an emphatic-nun suffix are skipped (it changes the stem's ending, e.g. يَبْلُوَ + نَّ)"""
    words = collections.defaultdict(list)          # word location -> its segments
    for line in open(path, encoding="utf-8"):
        parts = line.rstrip("\n").split("\t")
        if len(parts) == 4:
            words[parts[0].rsplit(":", 1)[0]].append(parts)

    idx = collections.defaultdict(lambda: collections.defaultdict(dict))
    for wloc, segs in words.items():
        if any("EMPH" in feats.split("|") and "SUFF" in feats.split("|") for _l, _f, _t, feats in segs):
            continue
        for loc, form, tag, feats in segs:
            if tag != "V":
                continue
            kv, flags = {}, set()
            for f in feats.split("|"):
                if ":" in f:
                    k, v = f.split(":", 1)
                    kv[k] = v
                else:
                    flags.add(f)
            if "ROOT" not in kv or "LEM" not in kv or SHOW_PERSON not in flags:
                continue
            tense = "past" if "PERF" in flags else "present" if "IMPF" in flags else None
            if tense is None or (tense == "present" and kv.get("MOOD") not in (None, "IND")):
                continue
            key = (kv["ROOT"], kv["LEM"], kv.get("VF", "1"), "PASS" in flags)
            sura, ayah, _w, _s = loc.split(":")
            entry = idx[key][tense].setdefault(form, [0, f"{sura}:{ayah}"])
            entry[0] += 1
    return idx


def attested_form(idx, key, tense):
    """Most common attested 3rd-person-masculine-singular form of this verb in this tense.
    -> (form, 'sura:ayah of first occurrence') or (None, None)"""
    cands = idx.get(key, {}).get(tense)
    if not cands:
        return None, None
    form, (_n, ref) = max(cands.items(), key=lambda kv: kv[1][0])
    return form, ref


def split_words(text, ayah):
    """-> list of (word, trail). Stop signs become the trail of the preceding word."""
    tokens = text.split()
    if ayah == 1:
        tokens = tokens[BISMILLAH_TOKENS:]
    out = []
    for t in tokens:
        if has_letter(t) or not out:
            out.append([t, ""])
        else:
            out[-1][1] += (" " if out[-1][1] else "") + t
    return out


SCHEMA = """
CREATE TABLE ayahs(
    ayah INTEGER PRIMARY KEY,
    arabic TEXT NOT NULL,
    translation TEXT NOT NULL,
    transliteration TEXT
);
CREATE TABLE words(
    word_id INTEGER PRIMARY KEY,
    ayah INTEGER NOT NULL REFERENCES ayahs(ayah),
    pos INTEGER NOT NULL,
    arabic TEXT NOT NULL,
    trail TEXT NOT NULL DEFAULT '',
    root TEXT,
    lemma TEXT,
    pos_tag TEXT,
    grammar TEXT,
    gloss TEXT,
    past_form TEXT, past_ref TEXT,
    present_form TEXT, present_ref TEXT,
    verified INTEGER NOT NULL DEFAULT 0,
    UNIQUE(ayah, pos)
);
CREATE TABLE segments(
    seg_id INTEGER PRIMARY KEY,
    word_id INTEGER NOT NULL REFERENCES words(word_id),
    seg INTEGER, form TEXT, tag TEXT, root TEXT, lemma TEXT, features TEXT
);
CREATE TABLE reciters(
    reciter_id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    kind TEXT NOT NULL,              -- ayah-json | ayah-db | surah-db (how the source file was laid out)
    sort_order INTEGER NOT NULL,
    source_file TEXT
);
CREATE TABLE recitations(
    reciter_id TEXT NOT NULL REFERENCES reciters(reciter_id),
    ayah INTEGER NOT NULL,
    url TEXT NOT NULL,               -- https link to an MP3 on a CDN (nothing is stored locally)
    start_ms INTEGER, end_ms INTEGER,-- only for whole-surah MP3s: where this ayah starts/ends inside it
    segments TEXT,                   -- JSON [[word_number, start_ms, end_ms], ...] or NULL if unusable
    PRIMARY KEY (reciter_id, ayah)
);
CREATE TABLE tafsir_sources(
    source_id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    sort_order INTEGER NOT NULL
);
CREATE TABLE tafsir(                 -- one row per commentary GROUP; a group can cover several ayahs
    source_id TEXT NOT NULL REFERENCES tafsir_sources(source_id),
    group_start INTEGER NOT NULL,
    group_end INTEGER NOT NULL,
    html TEXT NOT NULL,              -- already sanitized by import_tafsir.sanitize
    PRIMARY KEY (source_id, group_start)
);
CREATE INDEX idx_words_root  ON words(root);
CREATE INDEX idx_words_lemma ON words(lemma);
CREATE INDEX idx_words_ayah  ON words(ayah);
"""


def apply_corrections(db):
    if not CORRECTIONS.exists():
        return 0
    n = 0
    with open(CORRECTIONS, encoding="utf-8", newline="") as f:
        for row in csv.DictReader(f):
            if not row.get("ayah") or row["ayah"].startswith("#"):
                continue
            field = row["field"].strip()
            if field not in EDITABLE_FIELDS:
                raise SystemExit(f"corrections.csv: field '{field}' not allowed ({sorted(EDITABLE_FIELDS)})")
            value = row["new_value"].strip() or None
            cur = db.execute(f"UPDATE words SET {field}=? WHERE ayah=? AND pos=?",
                             (value, int(row["ayah"]), int(row["pos"])))
            if cur.rowcount != 1:
                raise SystemExit(f"corrections.csv: no word at ayah {row['ayah']} pos {row['pos']}")
            n += 1
    return n


def main():
    ar = load_tanzil(RAW / "quran-simple.txt")
    en = load_tanzil(RAW / "en.sahih.txt")
    morph = load_morph(RAW / "quran-morphology.txt")
    translit = load_transliteration(TRANSLIT_FILE)
    wbw = load_wbw(WBW_FILE)
    verb_idx = load_verb_forms(RAW / "quran-morphology.txt")
    assert len(ar) == N_AYAHS and len(en) == N_AYAHS, "expected 30 ayahs in each text file"

    if DB_PATH.exists():
        DB_PATH.unlink()
    db = sqlite3.connect(DB_PATH)
    db.executescript(SCHEMA)

    problems = []
    for a in range(1, N_AYAHS + 1):
        words = split_words(ar[a], a)
        shown = " ".join(w + (" " + t if t else "") for w, t in words)
        db.execute("INSERT INTO ayahs VALUES (?,?,?,?)", (a, shown, en[a], translit[a]))
        n_morph = len([k for k in morph if k[0] == a])
        if len(words) != n_morph:
            problems.append(f"ayah {a}: {len(words)} text words vs {n_morph} morphology words")
            continue
        if len(words) != len(wbw[a]):
            problems.append(f"ayah {a}: {len(words)} text words vs {len(wbw[a])} word-by-word meanings")
            continue
        for i, (tok, trail) in enumerate(words, start=1):
            segs = sorted(morph[(a, i)], key=lambda s: s["seg"])
            stem = (next((s for s in segs if s["root"]), None)
                    or next((s for s in segs if "PREF" not in s["flags"]), segs[0]))
            grammar = ",".join(f for f in stem["flags"] if f != "P")
            if stem["vform"]:
                grammar += f",form {stem['vform']}"
            past = present = (None, None)
            if stem["tag"] == "V" and stem["root"]:
                key = (stem["root"], stem["lemma"], stem["vform"] or "1", "PASS" in stem["flags"])
                past = attested_form(verb_idx, key, "past")
                present = attested_form(verb_idx, key, "present")
            cur = db.execute(
                "INSERT INTO words(ayah,pos,arabic,trail,root,lemma,pos_tag,grammar,gloss,"
                "past_form,past_ref,present_form,present_ref) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?)",
                (a, i, tok, trail, stem["root"], stem["lemma"], stem["tag"], grammar, wbw[a][i - 1],
                 past[0], past[1], present[0], present[1]))
            for s in segs:
                db.execute(
                    "INSERT INTO segments(word_id,seg,form,tag,root,lemma,features) VALUES (?,?,?,?,?,?,?)",
                    (cur.lastrowid, s["seg"], s["form"], s["tag"], s["root"], s["lemma"], s["raw"]))

    if problems:
        db.close()
        DB_PATH.unlink()
        raise SystemExit("ALIGNMENT PROBLEMS, DB not built:\n  " + "\n  ".join(problems))

    word_counts = dict(db.execute("SELECT ayah, COUNT(*) FROM words GROUP BY ayah").fetchall())
    import_audio.import_all(db, RECITATIONS_DIR, RECITERS_CONFIG, SURAH, word_counts)
    import_tafsir.import_all(db, TAFSIR_DIR, SURAH, N_AYAHS)

    n_fix = apply_corrections(db)
    db.commit()

    one = lambda sql: db.execute(sql).fetchone()[0]
    print(f"Built {DB_PATH.relative_to(ROOT_DIR)}")
    print(f"  ayahs: {one('select count(*) from ayahs')}")
    print(f"  words: {one('select count(*) from words')}")
    print(f"  words with a root: {one('select count(*) from words where root is not null')}")
    print(f"  distinct roots: {one('select count(distinct root) from words')}")
    print(f"  words with a word-by-word meaning: {one('select count(*) from words where gloss is not null')}")
    print(f"  ayahs with transliteration: {one('select count(*) from ayahs where transliteration is not null')}")
    n_verbs = one("select count(*) from words where pos_tag='V' and root is not null")
    print(f"  verbs: {n_verbs} | with a past form: {one('select count(*) from words where past_form is not null')}"
          f" | with a present form: {one('select count(*) from words where present_form is not null')}")
    print(f"  reciters: {one('select count(*) from reciters')} | tafsir sources: {one('select count(*) from tafsir_sources')}")
    print(f"  corrections applied: {n_fix}")
    db.close()


if __name__ == "__main__":
    sys.exit(main())
